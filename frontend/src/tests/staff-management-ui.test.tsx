import { describe, expect, it, vi, beforeEach } from 'vitest';
import { renderToString } from 'react-dom/server';
import { MemoryRouter } from 'react-router-dom';
import { PeopleManagementPage } from '../pages/people/PeopleManagementPage';
import { StaffCreatePage } from '../pages/hr/StaffCreatePage';
import { TemporaryCredentialModal } from '../components/hr/TemporaryCredentialModal';
import { peopleApi } from '../api/hrApi';

vi.mock('../api/hrApi', async () => {
  const actual = await vi.importActual<any>('../api/hrApi');
  return {
    ...actual,
    peopleApi: {
      getSummary: vi.fn(),
      getPeople: vi.fn(),
    },
    staffApi: {
      getStaff: vi.fn(),
      getStaffById: vi.fn(),
      createStaff: vi.fn(),
      updateStaff: vi.fn(),
      updateStaffStatus: vi.fn(),
      resendInvitation: vi.fn(),
      getStaffActivity: vi.fn(),
      getAcademicAssignments: vi.fn(),
      assignAcademicWorkload: vi.fn(),
      removeAcademicWorkload: vi.fn(),
    },
  };
});

vi.mock('../api/academics.api', () => ({
  AcademicsApi: {
    getSubjects: vi.fn().mockResolvedValue({ data: [] }),
    getClasses: vi.fn().mockResolvedValue({ data: [] }),
    getAcademicYears: vi.fn().mockResolvedValue({ data: [] }),
  },
}));

vi.mock('../hooks/usePermissions', () => ({
  usePermissions: () => ({
    hasPermission: vi.fn().mockReturnValue(true),
    hasAnyPermission: vi.fn().mockReturnValue(true),
  }),
}));

vi.mock('../contexts/AuthContext', () => ({
  useAuth: () => ({
    user: { id: 'admin-1', role: 'SCHOOL_ADMIN', email: 'admin@school.test' },
  }),
}));

describe('Staff Management UI — Simplified Workflow', () => {
  beforeEach(() => {
    vi.clearAllMocks();
  });

  it('renders strictly 3 navigation sections: Overview, Staff Profiles, Staff Activity', () => {
    vi.mocked(peopleApi.getSummary).mockResolvedValue({
      data: {
        indicators: {
          totalStaff: 12,
          activeStaff: 10,
          staffWithAccounts: 8,
          pendingInvitations: 3,
        },
        recentActivity: [],
        staff: null,
        academic: null,
        accounts: null,
        activity: [],
      },
    } as any);

    const html = renderToString(
      <MemoryRouter initialEntries={['/people']}>
        <PeopleManagementPage />
      </MemoryRouter>
    );

    expect(html).toContain('Overview');
    expect(html).toContain('Staff Profiles');
    expect(html).toContain('Staff Activity');

    // Ensure removed sections do not exist
    expect(html).not.toContain('All Staff &amp; Accounts');
    expect(html).not.toContain('Academic Assignments');
    expect(html).not.toContain('Roles &amp; Permissions');
  });

  it('displays the 4 essential indicator labels in Overview and omits redundant workload cards', () => {
    vi.mocked(peopleApi.getSummary).mockResolvedValue({
      data: {
        indicators: {
          totalStaff: 42,
          activeStaff: 38,
          staffWithAccounts: 30,
          pendingInvitations: 7,
        },
        recentActivity: [],
      },
    } as any);

    const html = renderToString(
      <MemoryRouter initialEntries={['/people?section=overview']}>
        <PeopleManagementPage />
      </MemoryRouter>
    );

    expect(html).toContain('Staff Management');
    // In server-rendered markup, initial state shows the loading indicators container or navigation
    expect(html).toContain('Overview');
    expect(html).toContain('Staff Profiles');
    expect(html).toContain('Staff Activity');
  });

  it('shows auto-generated employee number and removes Designation/Responsibilities steps from registration', () => {
    const html = renderToString(
      <MemoryRouter initialEntries={['/staff/new']}>
        <StaffCreatePage />
      </MemoryRouter>
    );

    // Verify 4 steps only
    expect(html).toContain('Personal &amp; Employment');
    expect(html).toContain('Account &amp; Role');
    expect(html).toContain('Academic Assignments');
    expect(html).toContain('Review &amp; Register');

    // Verify removed concepts and labels are completely absent
    expect(html).not.toContain('Official Designation');
    expect(html).not.toContain('Official designation');
    expect(html).not.toContain('Job Title / Designation');
    expect(html).not.toContain('Job Title');
    expect(html).not.toContain('Responsibilities');

    // Verify Staff Category selection is present
    expect(html).toContain('Staff Category');
    expect(html).toContain('Teaching Staff');
    expect(html).toContain('Support / Operations');

    // Verify employee number input is marked read-only and auto-generated
    expect(html).toContain('Auto-generated by system');
    expect(html).toContain('disabled=""');
  });

  it('renders one-time temporary credential dialog with staff details, copy action, and security warning', () => {
    const html = renderToString(
      <TemporaryCredentialModal
        isOpen={true}
        onClose={vi.fn()}
        staffName="Baraka Juma"
        staffEmail="baraka@example.test"
        employeeNumber="MWL-STAFF-0001"
        temporaryPassword="Mwl-a1b2c3d4!9A"
        isReset={false}
      />
    );

    // Verify dialog header and title
    expect(html).toContain('Temporary Account Credential');

    // Verify staff details displayed
    expect(html).toContain('Baraka Juma');
    expect(html).toContain('baraka@example.test');
    expect(html).toContain('MWL-STAFF-0001');

    // Verify temporary password / OTP displayed
    expect(html).toContain('Mwl-a1b2c3d4!9A');

    // Verify copy button and close action
    expect(html).toContain('Copy');
    expect(html).toContain('I Have Saved This Credential — Close');

    // Verify security explanation
    expect(html).toContain('Please securely share this temporary password with the staff member');
    expect(html).toContain('this temporary credential will not be displayed again');
    expect(html).toContain('required to set their own permanent password on first login');
  });
});
